"""Docs must not drift from the code.

`docs/rest-api.md` once claimed realtime events were "later phases" and omitted
`/plan`, `/consents`, `/audit` and both event transports — all of which shipped
long before anyone noticed. Prose cannot notice itself, so these tests compare
the documented surface against the routes the application actually registers, in
both directions: a route nobody documented is a gap, and a documented path that
does not exist is a lie.
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

from fastapi.testclient import TestClient

from actionmesh.api import create_app

DOCS = Path(__file__).resolve().parents[2] / "docs"
REST_API = DOCS / "rest-api.md"
ARCHITECTURE = DOCS / "architecture.md"

#: Auto-generated by FastAPI; not part of the documented surface.
FRAMEWORK_PATHS = {"/openapi.json", "/docs", "/docs/oauth2-redirect", "/redoc"}

ROUTE_IN_TEXT = re.compile(r"`(/[^`\s]*)`")


def registered_paths() -> set[str]:
    app = create_app()
    return {
        route.path
        for route in app.routes
        if getattr(route, "path", None) and route.path not in FRAMEWORK_PATHS
    }


def documented_paths(text: str) -> set[str]:
    return set(ROUTE_IN_TEXT.findall(text))


class TestRestApiDocsMatchTheCode(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not REST_API.exists():  # pragma: no cover - repository guard
            raise unittest.SkipTest("docs/rest-api.md is absent")
        cls.text = REST_API.read_text(encoding="utf-8")
        cls.routes = registered_paths()
        cls.documented = documented_paths(cls.text)

    def test_there_are_routes_to_compare(self) -> None:
        # Guards against the comparison silently passing on an empty app.
        self.assertGreater(len(self.routes), 10)
        self.assertIn("/health", self.routes)

    def test_every_route_is_documented(self) -> None:
        self.assertEqual(
            self.routes - self.documented,
            set(),
            "undocumented routes: add them to docs/rest-api.md",
        )

    def test_every_documented_path_is_a_real_route(self) -> None:
        self.assertEqual(
            self.documented - self.routes,
            set(),
            "docs/rest-api.md documents paths that do not exist",
        )

    def test_realtime_and_planning_are_not_described_as_future_work(self) -> None:
        # These shipped (C9) and (C18). The doc used to say otherwise.
        lowered = self.text.lower()
        self.assertNotIn("realtime events are later phases", lowered)
        for path in ("/events", "/ws/events", "/plan", "/consents", "/audit/verify"):
            self.assertIn(path, self.documented)

    def test_the_api_still_serves_health(self) -> None:
        # Cheap end-to-end confirmation that the app the docs describe builds.
        client = TestClient(create_app())
        self.assertEqual(client.get("/health").status_code, 200)


class TestArchitectureDocumentsTheTrustBoundary(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not ARCHITECTURE.exists():  # pragma: no cover - repository guard
            raise unittest.SkipTest("docs/architecture.md is absent")
        cls.text = ARCHITECTURE.read_text(encoding="utf-8")

    def test_the_planner_layer_is_listed(self) -> None:
        self.assertIn("actionmesh/core/planner.py", self.text)

    def test_it_states_that_a_plan_cannot_assert_authority(self) -> None:
        self.assertIn("no field", self.text.lower())
        self.assertIn("risk", self.text.lower())

    def test_it_does_not_claim_the_planner_is_a_language_model(self) -> None:
        self.assertIn("rule-based reference planner", self.text)


if __name__ == "__main__":
    unittest.main()